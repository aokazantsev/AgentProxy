import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENGINE = os.path.join(ROOT, "engine")
RUNTIME = os.path.join(ROOT, "runtime")
PYTHON_DIR = os.path.join(RUNTIME, "python")
DEV_DIR = os.path.join(RUNTIME, "dev")
STAMP = os.path.join(RUNTIME, "stamp.json")

PYTHON_VERSION = "3.13.16"
PYTHON_TAG = "313"
PYTHON_URL = "https://www.python.org/ftp/python/{0}/python-{0}-embed-amd64.zip".format(PYTHON_VERSION)
PYTHON_SHA256_FILE = os.path.join(ENGINE, "python-embed.sha256")

LOCKS = {
    "app": (os.path.join(ENGINE, "requirements.in"), os.path.join(ENGINE, "requirements.lock")),
    "dev": (os.path.join(ENGINE, "requirements-dev.in"), os.path.join(ENGINE, "requirements-dev.lock")),
}

PIP_PLATFORM = ["--platform", "win_amd64", "--python-version", PYTHON_VERSION.rsplit(".", 1)[0],
                "--implementation", "cp", "--only-binary=:all:"]


def sha256_of(path):
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def download(url, target):
    with urllib.request.urlopen(url, timeout=120) as response, open(target, "wb") as output:
        shutil.copyfileobj(response, output)


def resolve(requirements_in, extra_constraints):
    with tempfile.TemporaryDirectory() as scratch:
        report = os.path.join(scratch, "report.json")
        command = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
                   "--disable-pip-version-check", "--report", report, "--target", os.path.join(scratch, "t")]
        command += PIP_PLATFORM + ["-r", requirements_in]
        for constraint in extra_constraints:
            command += ["-c", constraint]
        subprocess.run(command, check=True)
        with open(report, encoding="utf-8") as stream:
            data = json.load(stream)
    pins = []
    for item in data["install"]:
        name = item["metadata"]["name"].lower().replace("_", "-")
        hashes = item["download_info"]["archive_info"]["hashes"]
        pins.append((name, item["metadata"]["version"], hashes["sha256"]))
    return sorted(pins)


def write_lock(path, pins):
    lines = ["# generated by tools/runtime.py lock, do not edit by hand"]
    for name, version, digest in pins:
        lines.append("{0}=={1} --hash=sha256:{2}".format(name, version, digest))
    with open(path, "w", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(lines) + "\n")


def lock():
    app_in, app_lock = LOCKS["app"]
    write_lock(app_lock, resolve(app_in, []))
    dev_in, dev_lock = LOCKS["dev"]
    app_names = {line.split("==")[0] for line in open(app_lock, encoding="utf-8") if "==" in line}
    dev_pins = [pin for pin in resolve(dev_in, [app_lock_constraints(app_lock)]) if pin[0] not in app_names]
    write_lock(dev_lock, dev_pins)
    print("locks written")


def app_lock_constraints(app_lock):
    path = os.path.join(tempfile.gettempdir(), "agentproxy-constraints.txt")
    with open(app_lock, encoding="utf-8") as source, open(path, "w", encoding="utf-8") as target:
        for line in source:
            if "==" in line:
                target.write(line.split(" ")[0] + "\n")
    return path


def install_python():
    if os.path.isdir(PYTHON_DIR):
        shutil.rmtree(PYTHON_DIR)
    os.makedirs(PYTHON_DIR)
    with tempfile.TemporaryDirectory() as scratch:
        archive = os.path.join(scratch, "python.zip")
        download(PYTHON_URL, archive)
        actual = sha256_of(archive)
        expected = open(PYTHON_SHA256_FILE, encoding="utf-8").read().strip() if os.path.exists(PYTHON_SHA256_FILE) else None
        if expected is None:
            with open(PYTHON_SHA256_FILE, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(actual + "\n")
            print("pinned python sha256 " + actual)
        elif expected != actual:
            raise SystemExit("python embed sha256 mismatch: expected {0}, got {1}".format(expected, actual))
        with zipfile.ZipFile(archive) as bundle:
            bundle.extractall(PYTHON_DIR)
    pth = os.path.join(PYTHON_DIR, "python{0}._pth".format(PYTHON_TAG))
    with open(pth, "w", encoding="utf-8", newline="\r\n") as stream:
        stream.write("python{0}.zip\n.\nLib\\site-packages\n..\\..\\engine\nimport site\n".format(PYTHON_TAG))


def pip_install(lock_path, target):
    os.makedirs(target, exist_ok=True)
    command = [sys.executable, "-m", "pip", "install", "--quiet", "--disable-pip-version-check", "--no-deps",
               "--require-hashes", "--target", target, "--upgrade"] + PIP_PLATFORM + ["-r", lock_path]
    subprocess.run(command, check=True)


def wanted_stamp():
    return {
        "python": PYTHON_VERSION,
        "app": sha256_of(LOCKS["app"][1]),
        "dev": sha256_of(LOCKS["dev"][1]),
    }


def fetch(force):
    stamp = wanted_stamp()
    if not force and os.path.exists(STAMP):
        with open(STAMP, encoding="utf-8") as stream:
            if json.load(stream) == stamp:
                print("runtime up to date")
                return
    install_python()
    pip_install(LOCKS["app"][1], os.path.join(PYTHON_DIR, "Lib", "site-packages"))
    if os.path.isdir(DEV_DIR):
        shutil.rmtree(DEV_DIR)
    pip_install(LOCKS["dev"][1], DEV_DIR)
    for cache in ("__pycache__",):
        for folder, dirs, _ in os.walk(PYTHON_DIR):
            if cache in dirs:
                shutil.rmtree(os.path.join(folder, cache))
    with open(STAMP, "w", encoding="utf-8") as stream:
        json.dump(stamp, stream)
    print("runtime ready: " + PYTHON_DIR)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["lock", "fetch"])
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    if args.command == "lock":
        lock()
    else:
        fetch(args.force)


if __name__ == "__main__":
    main()
